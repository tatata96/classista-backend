import { Controller, Get, Query, UseGuards } from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiForbiddenResponse,
  ApiOkResponse,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import { SupabaseAuthGuard } from '../auth/guards/supabase-auth.guard.js';
import { CurrentPartner } from '../partners/decorators/current-partner.decorator.js';
import { PartnerAccessGuard } from '../partners/guards/partner-access.guard.js';
import type { PartnerContext } from '../partners/types/partner-context.js';
import { ClassSessionsService } from './class-sessions.service.js';
import { ClassSessionResponseDto } from './dto/class-session-response.dto.js';
import { FindClassSessionsQueryDto } from './dto/find-class-sessions-query.dto.js';

// "/partner/..." has no :partnerId: PartnerAccessGuard resolves the partner
// from the authenticated user's own membership. OWNER and STAFF are equal.
@ApiTags('Partner class sessions')
@ApiBearerAuth()
@ApiUnauthorizedResponse({ description: 'Missing or invalid token' })
@ApiForbiddenResponse({
  description: 'Not a partner member, or the partner is inactive',
})
@UseGuards(SupabaseAuthGuard, PartnerAccessGuard)
@Controller('partner/class-sessions')
export class ClassSessionsController {
  constructor(private readonly classSessionsService: ClassSessionsService) {}

  @Get()
  @ApiOkResponse({
    description:
      "Lists the partner's already-generated sessions that start on the given Istanbul day (00:00 inclusive to next 00:00 exclusive), earliest first. Empty array when there are none. Nothing is generated by this request.",
    type: [ClassSessionResponseDto],
  })
  @ApiBadRequestResponse({
    description: 'date is missing, malformed, or not a real calendar date',
  })
  findByDate(
    @CurrentPartner() partner: PartnerContext,
    @Query() query: FindClassSessionsQueryDto,
  ): Promise<ClassSessionResponseDto[]> {
    return this.classSessionsService.findByDate(partner.partnerId, query.date);
  }
}
